import { defineType, defineField, defineArrayMember } from '../types';
import { standardBlock } from '../objects/portableText';

export const research = defineType({
  name: 'research',
  title: 'Research Report',
  type: 'document',
  fields: [
    defineField({
      name: 'workbookId',
      title: 'Workbook ID',
      type: 'string',
      readOnly: true,
      validation: (Rule) => Rule.required(),
      description: 'Authoritative inventory ID (e.g. RES-001).',
    }),
    defineField({
      name: 'title',
      title: 'Title',
      type: 'string',
      validation: (Rule) => Rule.required(),
      description: 'Full title of the research report.',
    }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      validation: (Rule) => Rule.required(),
      options: {
        source: 'title',
        maxLength: 96,
      },
      description: 'URL-safe identifier matching the original V1 path.',
    }),
    defineField({
      name: 'summary',
      title: 'Executive Summary',
      type: 'text',
      rows: 3,
      validation: (Rule) => Rule.required(),
      description: 'Concise abstract or executive summary of research findings.',
    }),
    defineField({
      name: 'status',
      title: 'Status',
      type: 'string',
      validation: (Rule) => Rule.required(),
      initialValue: 'draft',
      options: {
        list: [
          { title: 'Completed', value: 'Completed' },
          { title: 'In Progress', value: 'In Progress' },
          { title: 'Published', value: 'Published' },
          { title: 'Draft', value: 'Draft' },
        ],
      },
    }),
    defineField({
      name: 'publishedAt',
      title: 'Publication Date',
      type: 'datetime',
      validation: (Rule) => Rule.required(),
      description: 'Original publication date and time.',
    }),
    defineField({
      name: 'updatedAt',
      title: 'Last Updated Date',
      type: 'datetime',
      description: 'Date and time of subsequent revision, if applicable.',
    }),
    defineField({
      name: 'category',
      title: 'Category',
      type: 'string',
      validation: (Rule) => Rule.required(),
      description: 'Primary research domain category from V1 frontmatter.',
    }),
    defineField({
      name: 'tags',
      title: 'Tags',
      type: 'array',
      of: [defineArrayMember({ type: 'string' })],
      options: {
        layout: 'tags',
      },
      description: 'Topical classification keywords.',
    }),
    defineField({
      name: 'researchMethod',
      title: 'Research Methodology',
      type: 'string',
      description: 'Empirical or analytical methodology employed in the report.',
    }),
    defineField({
      name: 'lengthEstimateMinutes',
      title: 'Estimated Reading Time (Minutes)',
      type: 'number',
      description: 'Calculated or estimated reading time in minutes.',
    }),
    defineField({
      name: 'coverImage',
      title: 'Cover Image',
      type: 'object',
      fields: [
        defineField({ name: 'assetPath', title: 'Asset Path', type: 'string', validation: (Rule) => Rule.required() }),
        defineField({ name: 'alt', title: 'Alternative Text', type: 'string' }),
      ],
      description: 'Lead visual figure or cover graphic.',
    }),
    defineField({
      name: 'author',
      title: 'Author',
      type: 'reference',
      to: [{ type: 'author' }],
      description: 'Author attribution record.',
    }),
    defineField({
      name: 'topics',
      title: 'Taxonomy Topics',
      type: 'array',
      of: [defineArrayMember({ type: 'reference', to: [{ type: 'topic' }] })],
      description: 'Curated topics associated with this research work.',
    }),
    defineField({
      name: 'derivedPosts',
      title: 'Derived Writing / Essays',
      type: 'array',
      of: [defineArrayMember({ type: 'reference', to: [{ type: 'writing' }] })],
      description: 'Essays or articles derived from this research report (e.g. BLG-xxx).',
    }),
    defineField({
      name: 'relatedProjects',
      title: 'Related Projects',
      type: 'array',
      of: [defineArrayMember({ type: 'reference', to: [{ type: 'project' }] })],
      description: 'Software applications or practical case studies connected to this report.',
    }),
    defineField({
      name: 'sourceMaterial',
      title: 'Source Material References',
      type: 'array',
      of: [defineArrayMember({ type: 'sourceMaterialEntry' })],
      description: 'Primary datasets, whitepapers, or foundational material.',
    }),
    defineField({
      name: 'bibliographyHeading',
      title: 'Bibliography Section Heading',
      type: 'string',
      description: 'Original heading title for references (e.g. "Works Cited" or "References").',
    }),
    defineField({
      name: 'bibliography',
      title: 'Bibliography & References',
      type: 'array',
      of: [defineArrayMember({ type: 'bibliographyEntry' })],
      description: 'Lossless sequence of formal academic citations.',
    }),
    defineField({
      name: 'body',
      title: 'Body Content',
      type: 'array',
      validation: (Rule) => Rule.required(),
      of: [
        standardBlock,
        defineArrayMember({ type: 'formulaBlock' }),
        defineArrayMember({ type: 'imageBlock' }),
        defineArrayMember({ type: 'tableBlock' }),
        defineArrayMember({ type: 'mermaidBlock' }),
        defineArrayMember({ type: 'codeBlock' }),
        defineArrayMember({ type: 'dividerBlock' }),
      ],
      description: 'Portable Text body supporting equations, tables, figures, and rich text.',
    }),
    defineField({
      name: 'sourceArchive',
      title: 'Source Archive Provenance',
      type: 'sourceArchive',
      readOnly: true,
      validation: (Rule) => Rule.required(),
      description: 'Immutable V1 repository baseline metadata.',
    }),
    defineField({
      name: 'featured',
      title: 'Featured',
      type: 'boolean',
      initialValue: false,
      validation: (Rule) => Rule.required(),
      description: 'Editorial flag for homepage or showcase promotion. Defaults strictly to false.',
    }),
    defineField({
      name: 'editorialStatus',
      title: 'Editorial Lifecycle Status',
      type: 'string',
      initialValue: 'draft',
      options: {
        list: [
          { title: 'Draft', value: 'draft' },
          { title: 'In Review', value: 'in_review' },
          { title: 'Approved', value: 'approved' },
        ],
        layout: 'radio',
      },
      description: 'Content review state. Content is never automatically marked approved.',
    }),
    defineField({
      name: 'editorialNotes',
      title: 'Editorial Notes',
      type: 'text',
      description: 'Audit annotations, anomaly registers, or editorial review remarks.',
    }),
  ],
  preview: {
    select: {
      title: 'title',
      workbookId: 'workbookId',
      category: 'category',
    },
    prepare({ title, workbookId, category }) {
      return {
        title: title || 'Untitled Report',
        subtitle: `[${workbookId || 'NO-ID'}] ${category || 'Uncategorized'}`,
      };
    },
  },
});
